#!/bin/sh
# Build the SM83 side of the cart flash work (lane cartflash1). Outputs in build/:
#   netboot.mif.vmem / netboot_sameboy.bin   TEST-ONLY CGB boot ROM = stock boot ROM +
#       cf_netboot.inc (FPGA 2 KB / SameBoy 0x900). It fetches a WRAM program over the
#       network window (CF_LOAD, else GET cp/probe.bin) and never touches the cart itself.
#   cartprobe.bin          the READ-ONLY probe + backup dump (WRAM program, "SGWX" + code)
#   cartprobe_flashid.bin  the same + step 2 flash ID (autoselect/CFI): OWNER APPROVAL
#   cf_writer.bin / ../cf_writer_bin.h   the cart writer (WRAM program; C array for the ESP32)
# The boot ROM patching is the same as tools/nw/bootrom/make_shltest.sh (the DMG palette
# tables go to make room; DMG games get palette 0 in the test build). The stock
# reassembly is checked byte for byte against the FPGA's boot ROM first. Never flash a
# bitstream built with the test boot ROM.
set -eu
cd "$(dirname "$0")"
BR=${CWL_ROOT:?set_CWL_ROOT_to_your_work_folder}/tools/nw/bootrom                       # cgb_boot.asm, hardware.inc (read only)
VMEM=${VMEM:-${CWL_ROOT:?set_CWL_ROOT_to_your_work_folder}/tools/nw/bootrom/cgb_boot.mif.vmem.orig}   # pristine stock (fpga builds swap the worktree vmem)
mkdir -p build
gen() {   # $1 include file, $2 output asm
python3 - "$BR/cgb_boot.asm" "$1" "$2" <<'PY'
import sys
s = open(sys.argv[1]).read(); inc = sys.argv[2]; out = sys.argv[3]
hook = "NetBoot"
a = "Start:\n; Init stack pointer\n    ld sp, $fffe\n"
assert a in s
s = s.replace(a, a + "IF DEF(NWTEST)\n    call %s\nENDC\n" % hook, 1)
a = "GetInputPaletteIndex:\n"
i = s.index(a); j = s.index("LoadDMGTilemap:\n")
s = s[:i] + a + "IF DEF(NWTEST)\n    ret\nELSE\n" + s[i + len(a):j] + "ENDC\n" + s[j:]
a = "TitleChecksums:\n"; i = s.index(a); j = s.index("PaletteCombinations:\n")
s = s[:i] + "IF !DEF(NWTEST)\n" + s[i:j] + "ENDC\n" + s[j:]
a = "GetPaletteIndex:\n"; i = s.index(a); j = s.index("; optimizations in callers rely on this returning with b = 0\n")
s = s[:i] + a + "IF DEF(NWTEST)\n    xor a\n    ret\nELSE\n" + s[i + len(a):j] + "ENDC\n" + s[j:]
s = s.replace("BootEnd:\n", "IF DEF(NWTEST)\nINCLUDE \"%s\"\nENDC\n\nBootEnd:\n" % inc, 1)
s = s.replace("IF BootEnd > $900", "IF BootEnd > $800", 1)
open(out, 'w').write(s)
PY
}
gen cf_netboot.inc build/cgb_boot_netboot.asm
I="-I . -I $BR"
rgbasm -Wno-obsolete $I -o build/stock.o build/cgb_boot_netboot.asm
rgblink -o build/stock.bin build/stock.o
rgbasm -Wno-obsolete $I -D NWTEST -o build/netboot.o build/cgb_boot_netboot.asm
rgblink -m build/netboot.map -o build/netboot.bin build/netboot.o
prog() {   # $1 source, $2 output name, $3 end symbol, $4.. extra rgbasm flags
    src=$1; out=$2; endsym=$3; shift 3
    rgbasm -Wno-obsolete $I "$@" -o build/$out.o $src
    rgblink -n build/$out.sym -m build/$out.map -o build/$out.full build/$out.o
    python3 - build/$out.sym $endsym build/$out.full build/$out.bin <<'PY'
import sys
sym, endsym, full, out = sys.argv[1:]
end = None
for l in open(sym):
    p = l.split()
    if len(p) == 2 and p[1] == endsym:
        end = int(p[0].split(':')[1], 16)
assert end is not None, endsym
n = end - 0xC000
b = open(full, 'rb').read()[:n]
assert b[:4] == b"SGWX"
open(out, 'wb').write(b)
print("%-22s %5d bytes (WRAM $C000-$%04X)" % (out, n, end - 1))
PY
}
prog cartprobe.asm cartprobe CpWramEnd
prog cartprobe.asm cartprobe_flashid CpWramEnd -D CP_FLASHID
prog cf_writer.asm cf_writer WriterEnd
python3 - build/cf_writer.bin ../cf_writer_bin.h <<'PY'
import sys, hashlib
b = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as f:
    f.write("/* generated by make_sm83.sh from cf_writer.asm: the WRAM cart writer (sha256 %s) */\n" % hashlib.sha256(b).hexdigest()[:16])
    f.write("#include <stdint.h>\nstatic const uint8_t cf_writer_bin[%d] = {\n" % len(b))
    for i in range(0, len(b), 16):
        f.write("    " + ", ".join("0x%02X" % x for x in b[i:i + 16]) + ",\n")
    f.write("};\n")
PY
python3 - build/cartprobe.bin build/cartprobe_flashid.bin ../cf_probe_bin.h <<'PY'
import sys, hashlib
a, b, out = sys.argv[1:]
with open(out, 'w') as f:
    f.write("/* generated by make_sm83.sh from cartprobe.asm: the read-only probe and the flash-ID probe,\n"
            " * served by CF_LOAD in `cart probe` mode */\n#include <stdint.h>\n")
    for name, path in (("cf_probe_bin", a), ("cf_probe_flashid_bin", b)):
        d = open(path, 'rb').read()
        f.write("/* sha256 %s */\nstatic const uint8_t %s[%d] = {\n" % (hashlib.sha256(d).hexdigest()[:16], name, len(d)))
        for i in range(0, len(d), 16):
            f.write("    " + ", ".join("0x%02X" % x for x in d[i:i + 16]) + ",\n")
        f.write("};\n")
PY
python3 - "$VMEM" <<'PY'
import sys
ref = bytes(int(l.split()[0], 16) for l in open(sys.argv[1]) if l.strip())
st = open('build/stock.bin', 'rb').read()[:2048]
assert st == ref, "stock reassembly differs from the FPGA boot ROM"
t = open('build/netboot.bin', 'rb').read()
open('build/netboot.mif.vmem', 'w').write(''.join('%02X \r\n' % b for b in t[:2048]))
open('build/netboot_sameboy.bin', 'wb').write(t[:0x900])
print("stock reassembly identical; netboot boot ROM differs from stock in %d bytes" % sum(1 for x, y in zip(t[:2048], ref) if x != y))
PY
grep -E "BootEnd" build/netboot.map | head -2
shasum -a 256 build/netboot.mif.vmem build/cartprobe.bin build/cartprobe_flashid.bin build/cf_writer.bin
